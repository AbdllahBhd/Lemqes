#!/usr/bin/env python3
"""Generates supabase/tests/database/096-fold-vectors.sql from supabase/tests/fold_vectors.json.

The JSON is the single source of truth for the search fold and the name skeleton: the SQL
functions are asserted against it by the generated pgTAP file, the Dart ones by
flutter_app/test/features/geo/presentation/search_fold_test.dart. `--check` exits non-zero when
the checked-in 096 is stale (run by `npm run lint`).
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VECTORS = ROOT / "supabase/tests/fold_vectors.json"
OUT = ROOT / "supabase/tests/database/096-fold-vectors.sql"


def lit(s: str) -> str:
    # Invisible characters (harakat, tatweel, format controls) become U&'\XXXX' pieces so they
    # stay reviewable in the generated file.
    parts, run = [], ""
    for ch in s:
        o = ord(ch)
        if o < 0x20 or 0x7F <= o <= 0x9F or o == 0x0640 or 0x064B <= o <= 0x065F or 0x2000 <= o <= 0x206F:
            if run:
                parts.append("'" + run + "'")
                run = ""
            parts.append("U&'\\%04X'" % o)
        else:
            run += ch.replace("'", "''")
    if run or not parts:
        parts.append("'" + run + "'")
    return " || ".join(parts)


def render() -> str:
    cases = json.loads(VECTORS.read_text(encoding="utf-8"))
    lines = [
        "-- GENERATED by scripts/fold_vectors.py from supabase/tests/fold_vectors.json. Do not edit.",
        "begin;",
        "select plan(%d);" % (2 * len(cases)),
        "",
    ]
    for n, c in enumerate(cases, 1):
        for fn, key in (("f_search_fold", "fold"), ("f_name_skeleton", "skeleton")):
            lines.append(
                "select is(private.%s(%s), %s, %s);"
                % (fn, lit(c["input"]), lit(c[key]), lit("%s vector %d" % (fn, n)))
            )
    lines += ["", "select * from finish();", "rollback;", ""]
    return "\n".join(lines)


def main() -> int:
    text = render()
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("096-fold-vectors.sql is stale: run python3 scripts/fold_vectors.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
